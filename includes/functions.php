function formatCurrency(float|int|string $amount, ?string $currency = null): string
{
    $amount = (float)$amount;
    $symbol = CURRENCY_SYMBOL;
    return $symbol . number_format($amount, 2, '.', ',');
}

function getSetting(string $key, ?string $default = null): ?string
{
    static $settingsCache = null;

    if ($settingsCache === null) {
        $settingsCache = [];
        try {
            $db = getDB();
            $stmt = $db->query("SELECT `key`, `value` FROM settings");
            while ($row = $stmt->fetch()) {
                $settingsCache[$row['key']] = $row['value'];
            }
        } catch (Throwable $e) {
            Logger::error("Failed to load settings: " . $e->getMessage());
        }
    }

    return $settingsCache[$key] ?? $default;
}

function setSetting(string $key, string $value): bool
{
    try {
        $db = getDB();
        $stmt = $db->prepare("
            INSERT INTO settings (`key`, `value`, created_at, updated_at)
            VALUES (?, ?, NOW(), NOW())
            ON DUPLICATE KEY UPDATE `value` = VALUES(`value`), updated_at = NOW()
        ");
        return $stmt->execute([$key, $value]);
    } catch (Throwable $e) {
        Logger::error("Failed to save setting [{$key}]: " . $e->getMessage());
        return false;
    }
}

function flash(string $key, ?string $message = null): ?string
{
    if ($message !== null) {
        $_SESSION['flash'][$key] = $message;
        return null;
    }

    if (isset($_SESSION['flash'][$key])) {
        $msg = $_SESSION['flash'][$key];
        unset($_SESSION['flash'][$key]);
        return $msg;
    }

    return null;
}

function hasFlash(string $key): bool
{
    return isset($_SESSION['flash'][$key]);
}

function timeAgo(string $datetime): string
{
    $time = strtotime($datetime);
    if (!$time) {
        return 'Never';
    }
    $diff = time() - $time;
    if ($diff < 60) {
        return 'just now';
    }
    if ($diff < 3600) {
        $min = (int)($diff / 60);
        return $min . 'm ago';
    }
    if ($diff < 86400) {
        $hrs = (int)($diff / 3600);
        return $hrs . 'h ago';
    }
    if ($diff < 604800) {
        $days = (int)($diff / 86400);
        return $days . 'd ago';
    }
    return date('M j, Y', $time);
}

function getUnreadNotificationsCount(?int $userId): int
{
    if (!$userId) {
        return 0;
    }
    try {
        $db = getDB();
        $stmt = $db->prepare("
            SELECT COUNT(*) FROM notifications 
            WHERE (user_id = ? OR user_id IS NULL) AND is_read = 0
        ");
        $stmt->execute([$userId]);
        return (int)$stmt->fetchColumn();
    } catch (Throwable $e) {
        return 0;
    }
}

function jsonResponse(array $data, int $statusCode = 200): void
{
    http_response_code($statusCode);
    header('Content-Type: application/json; charset=utf-8');
    echo json_encode($data, JSON_UNESCAPED_SLASHES | JSON_PRETTY_PRINT);
    exit;
}

